import argparse
import json
from pathlib import Path
from unicodedata import category


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def normalize_dashes(value):
    return "".join("-" if category(char) == "Pd" or ord(char) in (183, 8722) else char for char in value)


def build_catalog(mapping, source):
    if any(not name.strip() for terms in mapping.values() for name in terms):
        raise ValueError("Localization keys must not be blank.")
    return {
        group: {normalize_dashes(name): normalize_dashes(source[table][key]) for name, (table, key) in terms.items()}
        for group, terms in mapping.items()
    }


def main():
    parser = argparse.ArgumentParser(description="Build the site's game terminology from extracted Evitania catalogs.")
    parser.add_argument("extracted", type=Path)
    parser.add_argument("locales", nargs="+")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / "i18n"
    mapping = read_json(target / "game-keys.json")
    try:
        catalogs = {
            locale: build_catalog(mapping, read_json(args.extracted / f"{locale}.json"))
            for locale in args.locales
        }
    except (KeyError, OSError, ValueError) as exc:
        parser.error(str(exc))
    for locale, catalog in catalogs.items():
        content = json.dumps(catalog, ensure_ascii=False, indent=2)
        (target / f"game-{locale}.js").write_text(
            f"// Generated by scripts/build-game-locales.py.\nexport default {content};\n",
            encoding="utf-8", newline="\n",
        )


if __name__ == "__main__":
    main()
